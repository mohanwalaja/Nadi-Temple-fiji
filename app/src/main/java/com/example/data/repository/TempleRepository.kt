    fun getTempleEvents(currentDate: LocalDate): List<TempleEvent> {
        // Return all events sorted chronologically by date
        val upcoming = allTempleSpecialEvents2026.filter { !it.date.isBefore(currentDate) }
        return if (upcoming.isNotEmpty()) upcoming else allTempleSpecialEvents2026
    }

    fun getAllTempleEvents(): List<TempleEvent> = allTempleSpecialEvents2026

    val savedEventsFlow: Flow<List<SavedTempleEventEntity>>? = templeEventDao?.getAllSavedEvents()

    suspend fun toggleEventSaved(eventId: String, isCurrentlySaved: Boolean) {
        if (templeEventDao == null) return
        if (isCurrentlySaved) {
            templeEventDao.removeEvent(eventId)
        } else {
            templeEventDao.saveEvent(SavedTempleEventEntity(eventId = eventId, isNotificationActive = true))
        }
    }
