    fun getAllFestivals(): List<HinduFestival> = allFestivals

    fun getFestivalById(id: String): HinduFestival? = allFestivals.firstOrNull { it.id == id }

    fun getUpcomingFestivals(currentDate: LocalDate, limit: Int = 5): List<Pair<HinduFestival, LocalDate>> {
        val currentYear = currentDate.year
        return allFestivals.map { fest ->
            var festDate = fest.calculateDateForYear(currentYear)
            if (festDate.isBefore(currentDate)) {
                festDate = fest.calculateDateForYear(currentYear + 1)
            }
            fest to festDate
        }.sortedBy { it.second }.take(limit)
    }
